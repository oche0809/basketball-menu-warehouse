// 最近追加の並びがわかるよう、登録日時を1日ずつずらす
export function createSampleMenus(): PracticeMenu[] {
  const base = Date.now()
  return samples.map((s, i) => {
    const date = new Date(base - (samples.length - i) * 86400000).toISOString()
    return { ...s, id: `sample-${i + 1}`, favorite: false, createdAt: date, updatedAt: date }
  })
}
