// 最近追加したメニューの一覧で、先生が自分で追加したメニューより上に来ないよう、登録日時は固定の過去日時にする
export function createLibraryMenus(): PracticeMenu[] {
  const base = Date.UTC(2026, 8, 1)
  return library.map((s, i) => {
    const date = new Date(base + i * 60000).toISOString()
    return { ...s, id: `lib-${String(i + 1).padStart(3, '0')}`, favorite: false, createdAt: date, updatedAt: date }
  })
}
